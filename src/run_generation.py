"""Unattended overnight driver: runs every cohort model sequentially.

Before each model it waits until (a) the model is available in Ollama and (b) the previous
model's output file is complete, so only one model occupies the GPU at a time.
Usage: python src/run_generation.py [--after codellama:7b-instruct] [--per-set 375]
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

from common import GEN, MODELS, ROOT

EXPECTED_PER_LANG_SET = 375


def available() -> set:
    with urllib.request.urlopen("http://127.0.0.1:11434/api/tags") as r:
        return {m["name"] for m in json.load(r)["models"]}


def out_file(model: str) -> Path:
    return GEN / (model.replace(":", "__").replace("/", "_") + ".jsonl")


def n_rows(model: str) -> int:
    p = out_file(model)
    return sum(1 for _ in open(p, encoding="utf-8")) if p.exists() else 0


def wait(pred, what: str, every: int = 60, limit_h: float = 12) -> bool:
    t0 = time.time()
    while not pred():
        if time.time() - t0 > limit_h * 3600:
            print(f"gave up waiting for {what}", flush=True)
            return False
        time.sleep(every)
    return True


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--after", default="", help="model currently being generated by another process")
    ap.add_argument("--per-set", type=int, default=EXPECTED_PER_LANG_SET)
    a = ap.parse_args()
    expected = a.per_set * 8
    models = [m for m in MODELS if m != a.after]
    prev = a.after or None
    for m in models:
        if prev:
            wait(lambda: n_rows(prev) >= expected, f"{prev} to finish", every=120, limit_h=24)
        name = m if ":" in m else f"{m}:latest"
        if not wait(lambda: name in available() or m in available(), f"{m} download", limit_h=6):
            prev = None
            continue
        if n_rows(m) >= expected:
            prev = m
            continue
        print(time.strftime("%H:%M"), "starting", m, flush=True)
        subprocess.run([sys.executable, "-u", str(ROOT / "src/02_generate.py"), "--models", m,
                        "--per-set", str(a.per_set), "--concurrency", "4"], check=False)
        prev = m
    print("all models done", flush=True)


if __name__ == "__main__":
    main()
