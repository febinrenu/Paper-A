"""Third round of review checks; every rule applied identically to both arms.

(a) Temporal audit of the outcome. Each malicious event is classified as
      verified  the malicious code demonstrably appeared after the cutoff: npm, the first affected version (or, for
                whole-package records, the first version after the cutoff) was published after it; PyPI, the first
                day with downloads in the public PyPI logs is after the cutoff
      pre       evidence of malicious or prior activity on or before the cutoff (npm affected version published on
                or before it; PyPI downloads on or before it)
      uncertain no timestamp available
    and the comparison is repeated on verified events only.
(b) Cluster bootstrap: names are resampled in clusters, (i) name families (ecosystem + first token; a control
    shares all but one token with its source name, so families contain both arms) and (ii) matched sets (a
    hallucinated name with its controls). 2,000 resamples; percentile intervals for the Mantel-Haenszel odds ratio.
(c) Natural-name controls: names generated by a token-bigram chain over real 2024 package names (so tokens follow
    each other as they do in real names), with the token-count distribution of the hallucinated names; excluded if
    in the 2024 snapshot, emitted by any model, or reported malicious on or before the cutoff. Outcome as always.
(d) Cumulative incidence of a first post-cutoff malware report, by month, in both arms.
(e) Absolute risk difference per 10,000 names (Newcombe hybrid-score interval).
Outputs: tables/u14_review3.csv, tables/u14_incidence.csv (aggregates only).
"""
from __future__ import annotations

import importlib
import json
import random
import re

import httpx
import numpy as np
import pandas as pd
from statsmodels.stats.contingency_tables import StratifiedTable
from statsmodels.stats.proportion import proportion_confint

from common import DERIVED, REGISTRY, TABLES, USER_AGENT

st = importlib.import_module("07_stats")
mech = importlib.import_module("10_mechanism")
det = importlib.import_module("17_detection")
rob = importlib.import_module("23_outcome_robustness")
CH = "https://sql-clickhouse.clickhouse.com/?user=demo"


def mh_or(tabs):
    t = StratifiedTable([x + (0.5 if (x[:, 0] == 0).any() else 0) for x in tabs])
    return t.oddsratio_pooled


def tables_for(h, c, hk, ck):
    out = []
    for e in ("npm", "pypi"):
        a, b = hk[h.eco == e], ck[c.eco == e]
        out.append(np.array([[a.sum(), len(a) - a.sum()], [b.sum(), len(b) - b.sum()]], dtype=float))
    return out


def newcombe(k1, n1, k0, n0):
    l1, u1 = proportion_confint(k1, n1, method="wilson")
    l0, u0 = proportion_confint(k0, n0, method="wilson")
    p1, p0 = k1 / n1, k0 / n0
    d = p1 - p0
    return d, d - np.sqrt((p1 - l1) ** 2 + (u0 - p0) ** 2), d + np.sqrt((u1 - p1) ** 2 + (p0 - l0) ** 2)


def first_download_day(names):
    if not names:
        return {}
    lst = ",".join("'" + n.replace("'", "") + "'" for n in names)
    r = httpx.post(CH, content=(f"SELECT project, min(date) FROM pypi.pypi_downloads_per_day WHERE project IN ({lst}) "
                                f"GROUP BY project FORMAT TSV").encode(), timeout=300)
    out = {}
    for line in r.text.splitlines():
        p, d = line.split("\t")
        out[p] = pd.Timestamp(d, tz="UTC")
    return out


def main() -> None:
    cut = st.CUTOFF
    out = []
    rec = mech.osv_records()
    post = rec[rec.published > cut]
    ids = post.groupby(["eco", "name"]).id.apply(list)
    first = post.groupby(["eco", "name"]).published.min()
    cache = det.cached()

    # ---------------- (a) temporal audit
    def classify(e, n):
        if e == "npm":
            t = det.npm_times(n, cache)
            vers = det.osv_versions(ids.get((e, n), []), cache)
            vt = sorted(det.ts(t[v]) for v in vers if v in t)
            if not vt:
                vt = sorted(x for x in (det.ts(v) for k, v in t.items() if k not in ("created", "modified", "unpublished")
                                        and not k.endswith("-security")) if x <= first[(e, n)])
                vt = [x for x in vt if x > cut] or vt
            if not vt:
                return "uncertain"
            return "verified" if vt[0] > cut else "pre"
        d = fdd.get(n)
        if d is None:
            return "uncertain"
        return "verified" if d > cut else "pre"

    sets = {w: (mech.hallucinated(cut, w), mech.controls(cut, w)) for w in ("all", "c1")}
    mal_py = sorted({n for h, c in sets.values() for d in (h, c) for n in d.name[(d.eco == "pypi") & d.mal_post]})
    fdd = first_download_day(mal_py)
    cls = {}
    for w, (h, c) in sets.items():
        for d in (h, c):
            for e, n in zip(d.eco[d.mal_post], d.name[d.mal_post]):
                if (e, n) not in cls:
                    cls[(e, n)] = classify(e, n)
    client = httpx.Client(headers={"User-Agent": USER_AGENT})
    for w, (h, c) in sets.items():
        counts = {}
        for arm, d in (("h", h), ("c", c)):
            ks = [cls[k] for k in zip(d.eco[d.mal_post], d.name[d.mal_post])]
            counts[arm] = pd.Series(ks).value_counts().to_dict()
        hk = pd.Series([m and cls.get(k) == "verified" for k, m in zip(zip(h.eco, h.name), h.mal_post)], index=h.index)
        ck = pd.Series([m and cls.get(k) == "verified" for k, m in zip(zip(c.eco, c.name), c.mal_post)], index=c.index)
        out.append({"set": w, "analysis": "verified_post_cutoff_only", **rob.mh(h, c, hk, ck), "detail": json.dumps(counts)})
        hk2 = pd.Series([m and cls.get(k) != "pre" for k, m in zip(zip(h.eco, h.name), h.mal_post)], index=h.index)
        ck2 = pd.Series([m and cls.get(k) != "pre" for k, m in zip(zip(c.eco, c.name), c.mal_post)], index=c.index)
        out.append({"set": w, "analysis": "excl_pre_cutoff_evidence", **rob.mh(h, c, hk2, ck2)})

    # ---------------- (b) cluster bootstrap
    rng = np.random.default_rng(20261126)
    for w, (h, c) in sets.items():
        files = {"all": ["controls.parquet", "controls_c1.parquet"], "c1": ["controls_c1.parquet"]}[w]
        link = pd.concat([pd.read_parquet(DERIVED / f)[["eco", "name", "matched_to"]] for f in files]).drop_duplicates(["eco", "name"])
        cc = c if "matched_to" in c else c.merge(link, on=["eco", "name"], how="left")
        fam = lambda e, n: e + ":" + re.split(r"[-_.]", n.split("/")[-1])[0]
        d = pd.concat([pd.DataFrame({"eco": h.eco, "y": h.mal_post.astype(int), "arm": 1,
                                     "family": [fam(e, n) for e, n in zip(h.eco, h.name)],
                                     "mset": [e + ":" + n for e, n in zip(h.eco, h.name)]}),
                       pd.DataFrame({"eco": cc.eco, "y": cc.mal_post.astype(int), "arm": 0,
                                     "family": [fam(e, n) for e, n in zip(cc.eco, cc.name)],
                                     "mset": [e + ":" + str(m) for e, m in zip(cc.eco, cc.matched_to)]})],
                      ignore_index=True)
        for unit in ("family", "mset"):
            g = d.groupby([unit, "eco", "arm"]).agg(n=("y", "size"), k=("y", "sum")).reset_index()
            piv = g.pivot_table(index=[unit, "eco"], columns="arm", values=["n", "k"], fill_value=0)
            piv.columns = [f"{a}{b}" for a, b in piv.columns]
            piv = piv.reset_index()
            arr = {e: piv[piv.eco == e][["k1", "n1", "k0", "n0"]].to_numpy() for e in ("npm", "pypi")}
            point = mh_or([np.array([[a[:, 0].sum(), a[:, 1].sum() - a[:, 0].sum()],
                                     [a[:, 2].sum(), a[:, 3].sum() - a[:, 2].sum()]]) for a in arr.values()])
            bs = []
            for _ in range(2000):
                tabs = []
                for e, a in arr.items():
                    s = a[rng.integers(0, len(a), len(a))]
                    tabs.append(np.array([[s[:, 0].sum(), s[:, 1].sum() - s[:, 0].sum()],
                                          [s[:, 2].sum(), s[:, 3].sum() - s[:, 2].sum()]]))
                bs.append(mh_or(tabs))
            lo, hi = np.percentile(bs, [2.5, 97.5])
            ev_clusters = int(((piv.k1 + piv.k0) > 0).sum())
            out.append({"set": w, "analysis": f"cluster_bootstrap_{unit}", "or": point, "or_lo": lo, "or_hi": hi,
                        "detail": json.dumps({"clusters": int(len(piv)), "clusters_with_event": ev_clusters})})

    # ---------------- (c) natural-name (token-bigram) controls
    names = pd.read_parquet(DERIVED / "names.parquet")
    emitted = {e: set(names.name[names.eco == e]) for e in ("npm", "pypi")}
    pre_mal = set(zip(rec.eco[rec.published <= cut], rec.name[rec.published <= cut]))
    h, _ = sets["all"]
    rows_nat = []
    for e in ("npm", "pypi"):
        snap = [x for x in (REGISTRY / f"{e}_2024.txt").read_text(encoding="utf-8").split("\n") if x]
        snapset = set(snap)
        rr = random.Random(1122)
        sample = snap if len(snap) <= 400_000 else rr.sample(snap, 400_000)
        starts, nxt = [], {}
        for nm in sample:
            if nm.startswith("@"):
                continue
            toks = [t for t in nm.split("-") if t]
            if len(toks) < 2:
                continue
            starts.append(toks[0])
            for a, b in zip(toks, toks[1:]):
                nxt.setdefault(a, []).append(b)
        hn = h[(h.eco == e) & ~h.name.str.startswith("@")]
        lens = hn.name.str.count("-").add(1).clip(upper=5).tolist()
        made = set()
        target = 4 * len(hn)
        tries = 0
        while len(made) < target and tries < 60 * target:
            tries += 1
            k = rr.choice(lens)
            toks = [rr.choice(starts)]
            ok = True
            while len(toks) < k:
                cand = nxt.get(toks[-1])
                if not cand:
                    ok = False
                    break
                toks.append(rr.choice(cand))
            if not ok or len(set(toks)) < len(toks):
                continue
            nm = "-".join(toks)
            if nm in snapset or nm in emitted[e] or (e, nm) in pre_mal or nm in made:
                continue
            made.add(nm)
        k_nat = sum((e, nm) in mech.osv_post(cut) for nm in made) if False else None
        postset = {n for (ee, n) in mech.osv_post(cut) if ee == e}
        k_nat = sum(nm in postset for nm in made)
        hk_, hn_ = int(hn.mal_post.sum()), len(hn)
        rows_nat.append((e, k_nat, len(made), hk_, hn_))
        out.append({"set": f"natural_{e}", "analysis": "natural_name_controls", "h_events": hk_, "h_n": hn_,
                    "c_events": k_nat, "c_n": len(made),
                    "or": ((hk_ / hn_) / (k_nat / len(made))) if k_nat else np.nan})
    tabs = [np.array([[hk_, hn_ - hk_], [k, n - k]]) for e, k, n, hk_, hn_ in rows_nat]
    t = StratifiedTable([x + (0.5 if (x[:, 0] == 0).any() else 0) for x in tabs])
    lo, hi = t.oddsratio_pooled_confint()
    out.append({"set": "all", "analysis": "natural_name_controls_pooled", "or": t.oddsratio_pooled, "or_lo": lo,
                "or_hi": hi, "p": t.test_null_odds().pvalue, "h_events": int(sum(r[3] for r in rows_nat)),
                "h_n": int(sum(r[4] for r in rows_nat)), "c_events": int(sum(r[1] for r in rows_nat)),
                "c_n": int(sum(r[2] for r in rows_nat))})

    # ---------------- (d) cumulative incidence by month
    inc = []
    months = pd.period_range("2024-04", "2026-11", freq="M")
    for w, (h, c) in sets.items():
        for arm, d in (("hallucinated", h), ("control", c)):
            ts = pd.Series([first.get(k, pd.NaT) if m else pd.NaT for k, m in zip(zip(d.eco, d.name), d.mal_post)])
            ts = pd.to_datetime(ts, utc=True).dt.tz_convert(None).dt.to_period("M")
            for m in months:
                k = int((ts <= m).sum())
                lo, hi = proportion_confint(k, len(d), method="wilson")
                inc.append({"set": w, "arm": arm, "month": str(m), "events": k, "n": len(d),
                            "cum_incidence": k / len(d), "lo": lo, "hi": hi})
    pd.DataFrame(inc).to_csv(TABLES / "u14_incidence.csv", index=False)

    # ---------------- (e) absolute risk difference
    for w, (h, c) in sets.items():
        k1, n1, k0, n0 = int(h.mal_post.sum()), len(h), int(c.mal_post.sum()), len(c)
        dd, lo, hi = newcombe(k1, n1, k0, n0)
        out.append({"set": w, "analysis": "risk_difference_per_10k", "or": dd * 1e4, "or_lo": lo * 1e4, "or_hi": hi * 1e4,
                    "h_events": k1, "h_n": n1, "c_events": k0, "c_n": n0})

    o = pd.DataFrame(out)
    o.to_csv(TABLES / "u14_review3.csv", index=False)
    with pd.option_context("display.width", 250, "display.max_colwidth", 90):
        print(o.to_string(index=False))


if __name__ == "__main__":
    main()
